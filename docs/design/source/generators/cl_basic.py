from cloudlib import *
b = Board('Cloud_Basic', 'Basic cloud diagram: a web app in one VPC', 1900, 1500,
  'Frames show where things live: edge, region, network, then a subnet for each trust level. Public parts face the internet, private parts do the work, the data tier is reachable only from the private one.')
us = comp(b, 850, 200, 'Customers', 'browsers', 'Browser', 'blue')
cz(b, 600, 330, 1100, 520, 'Edge', 'edge')
cd = comp(b, 850, 425, 'CDN', 'caches static files', 'CDN', 'violet')
cz(b, 150, 600, 1850, 1440, 'Region eu-west', 'region')
cz(b, 190, 680, 1400, 1400, 'VPC 10.0.0.0/16', 'vpc')
cz(b, 230, 750, 1360, 910, 'Public subnet', 'public')
cz(b, 230, 1000, 1360, 1170, 'Private subnet', 'private')
cz(b, 230, 1260, 1360, 1390, 'Data subnet', 'data')
lb = comp(b, 850, 830, 'Load balancer', 'spreads traffic', 'Load balancer', 'violet')
ap = comp(b, 550, 1085, 'App server A', 'container', 'Containers', 'blue')
aq = comp(b, 1150, 1085, 'App server B', 'container', 'Containers', 'blue')
db = comp(b, 550, 1325, 'Database', 'PostgreSQL', 'SQL database', 'green')
ca = comp(b, 1150, 1325, 'Cache', 'Redis', 'In-memory cache', 'teal')
st = comp(b, 1650, 1085, 'Object storage', 'images, uploads', 'Object storage', 'amber')
b.arrow([us.b(), cd.t()], 'main', 'HTTPS', (850, 275))
b.arrow([cd.b(), lb.t()], 'main', 'HTTPS, on a miss', (850, 640))
m = 953
b.arrow([(lb.cx - 70, lb.b()[1]), (lb.cx - 70, m), (ap.cx, m), ap.t()], 'main', 'HTTP', (ap.cx + 80, m))
b.arrow([(lb.cx + 70, lb.b()[1]), (lb.cx + 70, m), (aq.cx, m), aq.t()], 'next', 'HTTP', (aq.cx - 80, m))
b.arrow([ap.b(), db.t()], 'main', 'SQL', (ap.cx, 1210))
b.arrow([aq.b(), ca.t()], 'next', 'get, set', (aq.cx, 1210))
b.arrow([aq.r(), st.l()], 'next', 'files, HTTPS', (1480, 1085))
print(save9(b))
