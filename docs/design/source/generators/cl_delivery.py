from cloudlib import *
b = Board('Cloud_Delivery', 'Complete cloud diagram: food delivery on two availability zones', 2500, 1800,
  'The delivery platform on a managed cloud. Two zones mean one can fail and orders keep flowing. Blue is one order: from the phone, through the edge, into a zone, to the primary database. Violet is the event stream and the database copy.')
cu = comp(b, 650, 200, 'Customer app', 'iOS, Android', 'Mobile', 'blue')
rt = comp(b, 1045, 200, 'Restaurant tablet', 'kitchen screen', 'Laptop', 'green')
co = comp(b, 1440, 200, 'Courier app', 'iOS, Android', 'Mobile', 'teal')
cz(b, 750, 340, 1340, 530, 'Edge', 'edge')
cd = comp(b, 1045, 440, 'CDN and firewall', 'caching, bot filter', 'Firewall / WAF', 'violet')
cz(b, 150, 650, 2330, 1700, 'Region eu-west', 'region')
cz(b, 190, 720, 1900, 1660, 'VPC 10.0.0.0/16', 'vpc')
cz(b, 230, 790, 1030, 1620, 'Zone a', 'az')
cz(b, 1060, 790, 1860, 1620, 'Zone b', 'az')
for x0, x1, tag in ((250, 1010, 'a'), (1080, 1840, 'b')):
    cz(b, x0, 880, x1, 1050, 'Public subnet', 'public')
    cz(b, x0, 1130, x1, 1310, 'Private subnet', 'private')
    cz(b, x0, 1390, x1, 1560, 'Data subnet', 'data')
la = comp(b, 630, 965, 'Load balancer', 'zone a', 'Load balancer', 'violet')
lb = comp(b, 1460, 965, 'Load balancer', 'zone b', 'Load balancer', 'violet')
na = comp(b, 630, 1220, 'Kubernetes node', 'order and dispatch pods', 'Kubernetes', 'blue')
nb = comp(b, 1460, 1220, 'Kubernetes node', 'order and dispatch pods', 'Kubernetes', 'blue')
da = comp(b, 630, 1475, 'Primary database', 'PostgreSQL', 'SQL database', 'violet')
db = comp(b, 1460, 1475, 'Replica database', 'read only', 'SQL database', 'violet')
qu = comp(b, 2150, 1220, 'Event queue', 'order events', 'Message queue', 'amber')
b.arrow([cu.b(), (cu.cx, 290), (1000, 290), (1000, cd.t()[1])], 'main', 'HTTPS', (810, 290))
b.arrow([rt.b(), (1045, cd.t()[1])], 'next', 'HTTPS', (1045, 300))
b.arrow([co.b(), (co.cx, 290), (1090, 290), (1090, cd.t()[1])], 'next', 'HTTPS', (1270, 290))
b.arrow([(1000, cd.b()[1]), (1000, 600), (630, 600), la.t()], 'main', 'HTTPS', (815, 600))
b.arrow([(1090, cd.b()[1]), (1090, 600), (1460, 600), lb.t()], 'next', 'HTTPS', (1275, 600))
b.arrow([la.b(), na.t()], 'main', 'HTTP', (630, 1085))
b.arrow([lb.b(), nb.t()], 'next', 'HTTP', (1460, 1085))
b.arrow([na.b(), da.t()], 'main', 'SQL', (630, 1345))
b.arrow([nb.b(), db.t()], 'next', 'SQL, reads', (1460, 1345))
b.arrow([da.r(), db.l()], 'data', 'replication', (880, 1475))
b.arrow([nb.r(), qu.l()], 'data', 'order.placed', (1985, 1220))
print(save9(b))
