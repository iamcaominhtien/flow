from cloudlib import *
b = Board('Cloud_Network', 'Network diagram: offices joined to the cloud', 2500, 1450,
  'Two sites reach the private network over encrypted tunnels. Admins coming from the internet can only enter through the bastion in the DMZ. Blue is a head-office user reaching the database.')
cz(b, 150, 330, 800, 940, 'Head office', 'onprem')
cz(b, 150, 1040, 800, 1290, 'Branch restaurant', 'onprem')
st = comp(b, 475, 470, 'Staff laptops', 'office Wi-Fi', 'Laptop', 'blue')
fw = comp(b, 475, 760, 'Office firewall', 'allows VPN only', 'Firewall', 'gray')
br = comp(b, 475, 1165, 'Branch router', 'tablets and printer', 'Wi-Fi', 'teal')
cz(b, 1250, 270, 2350, 1390, 'Region eu-west', 'region')
cz(b, 1290, 350, 2310, 1350, 'VPC 10.0.0.0/16', 'vpc')
cz(b, 1330, 440, 2270, 630, 'DMZ subnet', 'dmz')
cz(b, 1330, 740, 2270, 930, 'Private subnet', 'private')
cz(b, 1330, 1040, 2270, 1230, 'Data subnet', 'data')
vg = comp(b, 1550, 535, 'VPN gateway', 'IPsec tunnels', 'Virtual network', 'violet')
bs = comp(b, 2050, 535, 'Bastion host', 'SSH jump server', 'Terminal', 'gray')
ad = comp(b, 1800, 835, 'Admin dashboard', 'internal tools', 'Dashboard', 'blue')
db = comp(b, 1800, 1135, 'Orders database', 'PostgreSQL', 'SQL database', 'violet')
ra = comp(b, 2050, 130, 'Remote admin', 'from the internet', 'Laptop', 'gray')
b.arrow([st.b(), fw.t()], 'main', 'office network', (475, 615))
